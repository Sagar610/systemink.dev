const byUsername = new Map(AUTHORS.map((author) => [author.username, author]));

export function getAuthor(username: string): AuthorRecord {
  const author = byUsername.get(username);
  if (!author) {
    throw new Error(`Unknown author: ${username}`);
  }
  return author;
}

export function staffAuthors(limit = 6): AuthorRecord[] {
  return [...AUTHORS].sort((a, b) => (b.followersCount || 0) - (a.followersCount || 0)).slice(0, limit);
}
